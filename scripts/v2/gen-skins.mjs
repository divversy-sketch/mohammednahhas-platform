#!/usr/bin/env node
// Generates the 10 platform skins from scripts/v2/skins.source.mjs:
//   src/v2/styles/skins.css  – colour/shape/font tokens per skin, light + dark
//   src/v2/skins.js          – the list the skin pickers and the font loader use
// Run after editing skins.source.mjs:  node scripts/v2/gen-skins.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SKINS, TOKEN_MAP, fullTokens } from './skins.source.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const EXTRA = {
  glass: '--nx-glass', glassLine: '--nx-glass-line', scrim: '--nx-scrim', shadow3: '--nx-shadow-3', glow: '--nx-glow',
  accentSolid: '--nx-copper-solid', accentSolidDeep: '--nx-copper-solid-deep', goldSolid: '--nx-gold-solid', goldSolidDeep: '--nx-gold-solid-deep',
  patinaSolid: '--nx-patina-solid', patinaSolidDeep: '--nx-patina-solid-deep', dangerSolid: '--nx-danger-solid', dangerSolidDeep: '--nx-danger-solid-deep',
};
const MAP = { ...TOKEN_MAP, ...EXTRA };
const HEAD_DISPLAY = new Set(['cinema', 'zumurrud', 'daftar', 'jari', 'malaki', 'zahri']);

const block = (sel, vars) => `${sel} {\n${vars.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}`;
const css = ['/* Generated by scripts/v2/gen-skins.mjs from scripts/v2/skins.source.mjs — do not edit by hand. */',
  '/* <html data-skin="…"> picks the skin; data-theme="light|dark" picks its day or night palette. */'];
for (const s of SKINS) {
  const [xs, sm, m, l, xl] = s.radius;
  const shape = [['--nx-r-xs', `${xs}px`], ['--nx-r-s', `${sm}px`], ['--nx-r-m', `${m}px`], ['--nx-r-l', `${l}px`], ['--nx-r-xl', `${xl}px`],
    ['--nx-f-ui', `${s.body}, system-ui, -apple-system, 'Segoe UI', Tahoma, sans-serif`], ['--nx-f-read', `${s.body}, system-ui, sans-serif`],
    ['--nx-f-cal', `${s.display}, ${s.body}, serif`], ['--nx-f-head', HEAD_DISPLAY.has(s.id) ? 'var(--nx-f-cal)' : 'var(--nx-f-ui)']];
  const tok = (mode) => Object.entries(fullTokens(s, mode)).filter(([k]) => MAP[k]).map(([k, v]) => [MAP[k], v]);
  css.push(`/* ${s.id} — ${s.name} */`);
  css.push(block(`:root[data-skin="${s.id}"]`, [...shape, ...tok('light'), ['color-scheme', 'light']]));
  css.push(block(`:root[data-skin="${s.id}"][data-theme="dark"]`, [...tok('dark'), ['color-scheme', 'dark']]));
}
fs.writeFileSync(path.join(ROOT, 'src/v2/styles/skins.css'), css.join('\n') + '\n');

const list = SKINS.map((s) => ({
  id: s.id, name: s.name, tagline: s.tagline, flavor: s.flavor, fonts: s.gf,
  light: { bg: s.light.bg, surface: s.light.surface, ink: s.light.ink, accent: s.light.accent, gold: s.light.gold2, patina: s.light.patina, night: s.light.night },
  dark: { bg: s.dark.bg, surface: s.dark.surface, ink: s.dark.ink, accent: s.dark.accent, gold: s.dark.gold2, patina: s.dark.patina, night: s.dark.night },
}));
fs.writeFileSync(path.join(ROOT, 'src/v2/skins.js'), `// Generated by scripts/v2/gen-skins.mjs — do not edit by hand.\n// The ten platform skins: name, flavour, Google Fonts query and swatches for the pickers.\nexport const DEFAULT_SKIN = 'cinema';\nexport const SKINS = ${JSON.stringify(list, null, 2)};\nexport const getSkin = (id) => SKINS.find((s) => s.id === id) || SKINS[0];\n`);
console.log(`skins.css + skins.js: ${SKINS.length} skins`);
